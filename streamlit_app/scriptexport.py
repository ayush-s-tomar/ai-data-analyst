"""Collect the generated code from a session into one runnable script."""
import re

_BLOCK = re.compile(r"```python\n(.*?)```", re.DOTALL)

HEADER = '''"""Generated by AI Data Analyst. Load your data into `df`, then run."""
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns

df = pd.read_csv({name!r})  # change the loader if your file is not a CSV

'''


def build_script(filename: str, messages: list) -> str:
    parts = [HEADER.format(name=filename)]
    question = ""
    for message in messages:
        if message.get("role") == "user":
            question = " ".join(str(message.get("content", "")).split())
        elif message.get("role") == "assistant":
            for block in _BLOCK.findall(message.get("content", "")):
                parts.append(f"# Question: {question}\n{block.strip()}\n")
    parts.append("plt.show()\n")
    return "\n".join(parts)
